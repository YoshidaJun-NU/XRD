def load_xrd_data_full(uploaded_file):
    try:
        content = ""
        for enc in ['utf-8', 'cp932', 'shift_jis']:
            try:
                uploaded_file.seek(0)
                content = uploaded_file.read().decode(enc)
                break
            except: continue
        if not content: return None
        lines = content.splitlines()
        data_start_idx = 0
        for i, line in enumerate(lines):
            parts = line.replace('\t', ',').replace(' ', ',').split(',')
            parts = [p for p in parts if p.strip()]
            if len(parts) >= 2:
                try:
                    float(parts[0].strip()); float(parts[1].strip())
                    data_start_idx = i
                    break
                except ValueError: continue
        uploaded_file.seek(0)
        df = pd.read_csv(uploaded_file, skiprows=data_start_idx, header=None, sep=None, engine='python')
        df = df.apply(pd.to_numeric, errors='coerce').dropna(axis=0, how='any')
        if df.empty: return None
        df.columns = [f"Column {i}" for i in range(df.shape[1])]
        return df
    except Exception as e:
        st.error(f"Error parsing {uploaded_file.name}: {e}")
        return None

def generate_gnuplot_script(selected_data, styles, x_range, y_offset, x_col, y_col):
    """gnuplot用スクリプトを生成する"""
    script = f"""# Gnuplot script generated by XRD Plotter Pro
set terminal pngcairo enhanced font 'Arial,12' size 800,600
set output 'xrd_plot.png'
set xlabel "2-theta (deg.)"
set ylabel "Intensity (a.u.)"
set xrange [{x_range[0]}:{x_range[1]}]
set key linestyle -1
"""
    plot_cmds = []
    for i, d in enumerate(selected_data):
        s = styles[d['name']]
        # gnuplot形式で各ファイルをプロットするコマンド (ファイル名は仮でdata.csvとする)
        # 実際にはすべてのデータを結合したひとつのCSVを参照する形に
        offset = i * y_offset
        color = s['color']
        plot_cmds.append(f"'processed_data.csv' u 1:({i+2} * {s['scale']} + {offset}) w l lc rgb '{color}' lw {s['lw']} title '{d['name']}'")
    
    script += "plot " + ", \\\n     ".join(plot_cmds)
    return script

